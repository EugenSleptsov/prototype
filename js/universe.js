function fmtSci(x) {
  if (!(x > 0)) return '0';
  let e = Math.floor(Math.log10(x)), m = x / Math.pow(10, e);
  if (m >= 9.95) { m /= 10; e++; }
  return m.toFixed(1) + '·10' + (e < 0 ? '⁻' + sup(-e) : sup(e));
}
function fmtGeV(T) {
  if (T >= 1) return (T >= 100 ? T.toFixed(0) : T.toFixed(1)) + ' ГэВ';
  return (T * 1000).toFixed(0) + ' МэВ';
}
